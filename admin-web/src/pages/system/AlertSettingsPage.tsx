import { useEffect, useMemo, useState } from 'react'
import { Link } from 'react-router-dom'
import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query'
import { BellRing, Hexagon, Gauge, WifiOff, Zap } from 'lucide-react'
import { toast } from 'sonner'
import { alertsApi, appSettingsApi } from '@/api/endpoints'
import { PageHeader } from '@/components/shared/PageHeader'
import { ErrorBlock, LoadingBlock } from '@/components/shared/page-states'
import { Badge } from '@/components/ui/badge'
import { Button } from '@/components/ui/button'
import { Card, CardContent, CardDescription, CardHeader, CardTitle } from '@/components/ui/card'
import { Switch } from '@/components/ui/switch'
import { Label } from '@/components/ui/label'

const ALERT_TYPES = [
  { key: 'speeding', label: 'Speeding', icon: Gauge, hint: 'Triggered when vehicle speed exceeds its limit.' },
  { key: 'geofence', label: 'Geofence entry/exit', icon: Hexagon, hint: 'Generated by the real-time geofence engine.' },
  { key: 'offline', label: 'Device offline', icon: WifiOff, hint: 'Raised when GPS devices stop communicating.' },
  { key: 'ignition', label: 'Ignition / movement', icon: Zap, hint: 'Ignition and movement-related events.' },
  { key: 'system', label: 'System', icon: BellRing, hint: 'Platform and administrative notifications.' },
] as const

export function AlertSettingsPage() {
  const qc = useQueryClient()
  const alerts = useQuery({
    queryKey: ['alerts-settings-summary'],
    queryFn: () => alertsApi.list({ limit: 100, page: 1 }),
  })
  const settings = useQuery({
    queryKey: ['app-settings-alerts'],
    queryFn: () =>
      appSettingsApi.get() as Promise<{
        general?: Record<string, unknown>
        localization?: Record<string, unknown>
        notifications?: Record<string, boolean>
        appearance?: Record<string, unknown>
        system?: Record<string, unknown>
      }>,
  })

  const [notifications, setNotifications] = useState({
    email: true,
    push: false,
    systemAlerts: true,
  })

  useEffect(() => {
    const n = settings.data?.notifications
    if (n) {
      setNotifications({
        email: n.email !== false,
        push: Boolean(n.push),
        systemAlerts: n.systemAlerts !== false,
      })
    }
  }, [settings.data])

  const counts = useMemo(() => {
    const map: Record<string, number> = {}
    for (const a of alerts.data?.items ?? []) {
      map[a.type] = (map[a.type] || 0) + 1
    }
    return map
  }, [alerts.data])

  const save = useMutation({
    mutationFn: async () =>
      appSettingsApi.update({
        general: settings.data?.general,
        localization: settings.data?.localization,
        appearance: settings.data?.appearance,
        system: settings.data?.system,
        notifications,
      }),
    onSuccess: async () => {
      toast.success('Alert notification preferences saved')
      await qc.invalidateQueries({ queryKey: ['app-settings-alerts'] })
      await qc.invalidateQueries({ queryKey: ['admin-app-settings'] })
    },
    onError: () => toast.error('Could not save alert settings'),
  })

  if (alerts.isLoading || settings.isLoading) return <LoadingBlock label="Loading alert settings…" />
  if (alerts.isError) {
    return <ErrorBlock message="Could not load alert data." onRetry={() => void alerts.refetch()} />
  }

  return (
    <div className="space-y-6">
      <PageHeader
        icon={BellRing}
        title="Alert Settings"
        description="Notification channels and live alert-type activity across your fleet."
        breadcrumbs={[{ label: 'Alerts', href: '/alerts' }, { label: 'Settings' }]}
        actions={
          <Button asChild variant="secondary">
            <Link to="/alerts">Open alert inbox</Link>
          </Button>
        }
      />

      <div className="grid gap-6 lg:grid-cols-2">
        <Card>
          <CardHeader>
            <CardTitle>Notification channels</CardTitle>
            <CardDescription>Stored in application settings and applied platform-wide.</CardDescription>
          </CardHeader>
          <CardContent className="space-y-4">
            {(
              [
                ['email', 'Email notifications'],
                ['push', 'Push notifications'],
                ['systemAlerts', 'In-app system alerts'],
              ] as const
            ).map(([key, label]) => (
              <div key={key} className="flex items-center justify-between rounded-xl border border-[var(--border)] px-4 py-3">
                <Label htmlFor={`alert-${key}`}>{label}</Label>
                <Switch
                  id={`alert-${key}`}
                  checked={notifications[key]}
                  onCheckedChange={(v) => setNotifications((n) => ({ ...n, [key]: v }))}
                />
              </div>
            ))}
            <Button disabled={save.isPending} onClick={() => save.mutate()}>
              {save.isPending ? 'Saving…' : 'Save preferences'}
            </Button>
          </CardContent>
        </Card>

        <Card>
          <CardHeader>
            <CardTitle>Alert types in use</CardTitle>
            <CardDescription>Counts from recent alert records in MongoDB.</CardDescription>
          </CardHeader>
          <CardContent className="space-y-3">
            {ALERT_TYPES.map(({ key, label, icon: Icon, hint }) => (
              <div
                key={key}
                className="flex items-start gap-3 rounded-xl border border-[var(--border)] bg-[var(--background)]/50 p-3"
              >
                <div className="flex h-9 w-9 items-center justify-center rounded-lg bg-[var(--primary-soft)] text-[var(--primary)]">
                  <Icon className="h-4 w-4" />
                </div>
                <div className="min-w-0 flex-1">
                  <div className="flex items-center justify-between gap-2">
                    <p className="font-medium">{label}</p>
                    <Badge variant="secondary">{counts[key] ?? 0}</Badge>
                  </div>
                  <p className="text-xs text-[var(--muted)]">{hint}</p>
                </div>
              </div>
            ))}
          </CardContent>
        </Card>
      </div>
    </div>
  )
}
